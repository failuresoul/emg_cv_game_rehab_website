"""Writes THIRD_PARTY_NOTICES.md (Day 20): the licence of every runtime dependency, read from the
installed packages (web/node_modules and this Python environment), and the assets and models the
app uses at run time. Run from server/ after changing a dependency:

    python scripts/third_party_notices.py
"""

import json
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / "web"
OUT = ROOT / "THIRD_PARTY_NOTICES.md"


def web_runtime() -> list[tuple[str, str, str]]:
    package = json.loads((WEB / "package.json").read_text(encoding="utf-8"))
    rows = []
    for name, version in sorted(package.get("dependencies", {}).items()):
        info = json.loads((WEB / "node_modules" / name / "package.json").read_text(encoding="utf-8"))
        licence = info.get("license") or info.get("licenses") or "see package"
        rows.append((name, version, str(licence)))
    return rows


def python_runtime() -> list[tuple[str, str, str]]:
    rows = []
    for line in (ROOT / "server" / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        name = re.split(r"[\[=<>~ ]", line, maxsplit=1)[0]
        if name in {"pytest", "pytest-cov", "httpx"}:
            continue  # tests only
        meta = metadata.metadata(name)
        licence = meta.get("License-Expression") or meta.get("License") or ""
        if not licence or len(licence) > 60:
            classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
            licence = ", ".join(classifiers) or "see package"
        rows.append((name, metadata.version(name), licence))
    return rows


ASSETS = [
    ("MediaPipe Tasks Vision (WASM, from cdn.jsdelivr.net)", "1.2.0", "Apache-2.0", "Google"),
    ("MediaPipe Hand Landmarker and Pose Landmarker (lite) models", "float16", "Apache-2.0", "Google; see the models' model cards"),
    ("Inter font (Google Fonts)", "", "SIL Open Font License 1.1", "Rasmus Andersson"),
    ("Noto Sans Bengali font (Google Fonts)", "", "SIL Open Font License 1.1", "Google"),
    ("Lucide icons (lucide-react)", "", "ISC", "Lucide contributors"),
    ("Ollama (separate program, not bundled)", "", "MIT", "Ollama"),
    ("Language model qwen3.5:4b (pulled into Ollama, not bundled)", "", "VERIFY: see the model card on ollama.com / Hugging Face before release (Qwen models are usually Apache-2.0, but check this one)", "Alibaba Cloud (Qwen team)"),
]


def table(rows: list[tuple[str, ...]], headers: list[str]) -> list[str]:
    return ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |",
            *("| " + " | ".join(cell.replace("|", "/") for cell in row) + " |" for row in rows)]


def main() -> int:
    lines = ["# Third-party notices", "",
             "MuVi Rehab uses the following third-party software, assets and models. Their licences apply to them; "
             "the licence texts are in each package (web/node_modules, the Python environment) or on the project's page. "
             "Generated by `server/scripts/third_party_notices.py` from the installed packages; development-only tools "
             "(linters, test runners, build tools) are not distributed and are not listed.", "",
             "## Web app (bundled into the browser build)", "", *table(web_runtime(), ["Package", "Version", "Licence"]), "",
             "## Server (Python)", "", *table(python_runtime(), ["Package", "Version", "Licence"]), "",
             "## Assets, models and programs used at run time", "", *table(ASSETS, ["Item", "Version", "Licence", "By"]), "",
             "The language model is not part of MuVi Rehab: Ollama downloads it from its library when you pull it "
             "(docs/llm-model-choice.md). Check its licence and acceptable-use terms on the model card for your use.", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
