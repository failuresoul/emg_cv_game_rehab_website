"""Writes sparc.json: fixed SPARC test vectors shared by the web app and the server.

Run from the repository root with any Python 3.11+ (no packages needed):

    python shared/test-vectors/generate_sparc_vectors.py

This is a deliberately plain reference: a direct DFT instead of an FFT, so it checks the web
app's FFT rather than copying it. The web app (web/src/metrics/sparc.ts) and the server's
Python version (Day 11) must both reproduce every `expected` value to within `tolerance`.

SPARC follows Balasubramanian, Melendez-Calderon, Roby-Brami and Burdet (2015), "On the analysis
of movement smoothness", Journal of NeuroEngineering and Rehabilitation 12:112,
https://doi.org/10.1186/s12984-015-0090-9, with the parameters stated in "method" below.
"""

import json
import math
from pathlib import Path

OUT = Path(__file__).with_name("sparc.json")
RATE_HZ = 60.0
PAD_LEVEL = 4
CUTOFF_HZ = 10.0
AMPLITUDE_THRESHOLD = 0.05
CAMERA_STEP_MS = 1000 / 30


def min_jerk_speed(t_ms: float, start_ms: float, duration_ms: float, distance: float) -> float:
    """Speed (SW/s) of a minimum-jerk movement of `distance` SW."""
    tau = (t_ms - start_ms) / duration_ms
    if tau <= 0 or tau >= 1:
        return 0.0
    return distance / (duration_ms / 1000) * 30 * tau**2 * (1 - tau) ** 2


def camera_times(duration_ms: float) -> list[float]:
    """About 30 Hz, like the webcam, so the inputs need resampling to 60 Hz."""
    times = [round(i * CAMERA_STEP_MS, 1) for i in range(int(duration_ms / CAMERA_STEP_MS) + 1)]
    return times if times[-1] >= duration_ms else [*times, duration_ms]


def lcg(seed: int):
    """A fixed pseudo-random sequence, the same in any language: values from -1 to 1."""
    state = seed
    while True:
        state = (1103515245 * state + 12345) % 2**31
        yield state / 2**30 - 1


def case_inputs() -> dict[str, list[list[float]]]:
    reach = [[t, round(min_jerk_speed(t, 0, 1000, 0.6), 6)] for t in camera_times(1000)]
    two = [
        [t, round(min_jerk_speed(t, 0, 700, 0.4) + min_jerk_speed(t, 500, 800, 0.2), 6)]
        for t in camera_times(1300)
    ]
    noise = lcg(20261110)
    noisy = [[t, round(max(0.0, v + 0.06 * next(noise)), 6)] for t, v in reach]
    return {"min_jerk_reach": reach, "two_sub_movements": two, "noisy_reach": noisy}


def resample(samples: list[list[float]], rate_hz: float) -> tuple[list[float], float]:
    """Linear interpolation onto evenly spaced times from the first to the last sample.

    The number of points is round(duration * rate) + 1, so both endpoints are kept exactly and
    the actual rate is (points - 1) / duration, within a fraction of a percent of rate_hz.
    """
    t0, t_end = samples[0][0], samples[-1][0]
    duration_s = (t_end - t0) / 1000
    count = max(2, round(duration_s * rate_hz) + 1)
    values: list[float] = []
    j = 0
    for i in range(count):
        t = t0 + (t_end - t0) * i / (count - 1)
        while j < len(samples) - 2 and samples[j + 1][0] < t:
            j += 1
        (ta, va), (tb, vb) = samples[j], samples[j + 1]
        share = 0.0 if tb == ta else (t - ta) / (tb - ta)
        values.append(va + (vb - va) * min(1.0, max(0.0, share)))
    return values, (count - 1) / duration_s


def dft_magnitude(values: list[float], size: int) -> list[float]:
    padded = values + [0.0] * (size - len(values))
    out = []
    for k in range(size):
        re = im = 0.0
        for n, value in enumerate(padded):
            angle = -2 * math.pi * k * n / size
            re += value * math.cos(angle)
            im += value * math.sin(angle)
        out.append(math.hypot(re, im))
    return out


def sparc(samples: list[list[float]]) -> dict[str, float]:
    values, fs = resample(samples, RATE_HZ)
    size = 2 ** (math.ceil(math.log2(len(values))) + PAD_LEVEL)
    magnitude = dft_magnitude(values, size)
    normalised = [m / magnitude[0] for m in magnitude]
    freqs = [k * fs / size for k in range(size)]
    within = [k for k in range(size) if freqs[k] <= CUTOFF_HZ]
    last = max(k for k in within if normalised[k] >= AMPLITUDE_THRESHOLD)
    span = freqs[last] - freqs[0]
    arc = 0.0
    for k in range(1, last + 1):
        df = (freqs[k] - freqs[k - 1]) / span
        dm = normalised[k] - normalised[k - 1]
        arc += math.hypot(df, dm)
    return {
        "sparc": -arc,
        "resampled_count": len(values),
        "rate_hz": fs,
        "fft_size": size,
        "cutoff_hz": freqs[last],
    }


def main() -> None:
    cases = []
    for name, samples in case_inputs().items():
        cases.append({"name": name, "speed": samples, "expected": sparc(samples)})
    document = {
        "description": (
            "SPARC test vectors. Each input is a speed profile as [t_ms, speed_sw_s] at about "
            "30 Hz. Generated by shared/test-vectors/generate_sparc_vectors.py."
        ),
        "method": {
            "resample_hz": RATE_HZ,
            "pad_level": PAD_LEVEL,
            "cutoff_hz": CUTOFF_HZ,
            "amplitude_threshold": AMPLITUDE_THRESHOLD,
            "normalise_by": "magnitude at 0 Hz",
            "reference": "Balasubramanian et al. 2015, J NeuroEng Rehabil 12:112",
        },
        "tolerance": 1e-6,
        "cases": cases,
    }
    OUT.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8", newline="\n")
    for case in cases:
        print(f"{case['name']}: {case['expected']['sparc']:.6f}")


if __name__ == "__main__":
    main()
